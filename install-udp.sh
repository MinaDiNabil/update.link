package main

// udpgw server (badvpn's protocol). In the hysteria modes the app's tun2socks
// sends every UDP packet of the phone (DNS, games, calls, QUIC) over one TCP
// connection that it opens through the tunnel to 127.0.0.1:7300 on the
// server, its "Udpgw" setting. Without something listening there, those
// modes carry TCP only.
//
// Both directions are frames of
//
//	Len u16 LE | Flags u8 | ConID u16 LE | Addr | Data
//
// Addr being an IPv4 address and port (IPv6 with flagIPv6), in network
// order. A ConID stands for one UDP socket of the phone; replies carry the
// address the phone sent to.

import (
	"bufio"
	"encoding/binary"
	"flag"
	"io"
	"log"
	"net"
	"net/netip"
	"os"
	"strings"
	"sync"
	"time"
)

const (
	gwKeepalive = 0x01
	gwRebind    = 0x02
	gwDNS       = 0x04
	gwIPv6      = 0x08

	gwMaxConns = 512
	gwIdle     = 90 * time.Second
	// A TCP connection that carried nothing for this long, keepalives
	// included (tun2socks sends one every 10 s), has lost its client.
	gwClientIdle = 5 * time.Minute
)

type gwConn struct {
	pc   *net.UDPConn
	addr []byte // as the client wrote it: echoed in replies
	last time.Time
}

// systemDNS is where packets flagged as DNS go ("transparent DNS": the phone
// asks whatever server its network told it, this server's own resolver
// answers).
func systemDNS() netip.AddrPort {
	if f, err := os.Open("/etc/resolv.conf"); err == nil {
		defer f.Close()
		sc := bufio.NewScanner(f)
		for sc.Scan() {
			p := strings.Fields(sc.Text())
			if len(p) >= 2 && p[0] == "nameserver" {
				if a, err := netip.ParseAddr(p[1]); err == nil {
					return netip.AddrPortFrom(a, 53)
				}
			}
		}
	}
	return netip.MustParseAddrPort("8.8.8.8:53")
}

func serveGwClient(c net.Conn, dns netip.AddrPort) {
	defer c.Close()
	var wmu, mu sync.Mutex
	conns := map[uint16]*gwConn{}
	defer func() {
		mu.Lock()
		for _, u := range conns {
			u.pc.Close()
		}
		conns = nil
		mu.Unlock()
	}()

	reply := func(id uint16, flags byte, addr, data []byte) {
		n := 3 + len(addr) + len(data)
		if n > 0xffff {
			return
		}
		f := make([]byte, 2+n)
		binary.LittleEndian.PutUint16(f, uint16(n))
		f[2] = flags
		binary.LittleEndian.PutUint16(f[3:], id)
		copy(f[5:], addr)
		copy(f[5+len(addr):], data)
		wmu.Lock()
		_ = c.SetWriteDeadline(time.Now().Add(30 * time.Second))
		_, err := c.Write(f)
		wmu.Unlock()
		if err != nil {
			c.Close()
		}
	}

	r := bufio.NewReaderSize(c, 64<<10)
	hdr := make([]byte, 2)
	buf := make([]byte, 0xffff)
	for {
		_ = c.SetReadDeadline(time.Now().Add(gwClientIdle))
		if _, err := io.ReadFull(r, hdr); err != nil {
			return
		}
		n := int(binary.LittleEndian.Uint16(hdr))
		if _, err := io.ReadFull(r, buf[:n]); err != nil {
			return
		}
		if n < 3 {
			continue
		}
		flags := buf[0]
		id := binary.LittleEndian.Uint16(buf[1:3])
		if flags&gwKeepalive != 0 {
			continue
		}
		alen := 6
		if flags&gwIPv6 != 0 {
			alen = 18
		}
		if n < 3+alen {
			continue
		}
		addr := buf[3 : 3+alen]
		data := buf[3+alen : n]
		ip, _ := netip.AddrFromSlice(addr[:alen-2])
		dst := netip.AddrPortFrom(ip, binary.BigEndian.Uint16(addr[alen-2:]))
		if flags&gwDNS != 0 {
			dst = dns
		}

		now := time.Now()
		mu.Lock()
		u := conns[id]
		if u != nil && (flags&gwRebind != 0 || string(u.addr) != string(addr)) {
			u.pc.Close()
			delete(conns, id)
			u = nil
		}
		if u == nil {
			if len(conns) >= gwMaxConns {
				// Make room: drop the one idle longest.
				var oldID uint16
				var old *gwConn
				for k, v := range conns {
					if old == nil || v.last.Before(old.last) {
						oldID, old = k, v
					}
				}
				old.pc.Close()
				delete(conns, oldID)
			}
			pc, err := net.DialUDP("udp", nil, net.UDPAddrFromAddrPort(dst))
			if err != nil {
				mu.Unlock()
				continue
			}
			u = &gwConn{pc: pc, addr: append([]byte(nil), addr...), last: now}
			conns[id] = u
			go func(id uint16, u *gwConn, rflags byte) {
				rb := make([]byte, 0xffff)
				for {
					_ = u.pc.SetReadDeadline(time.Now().Add(gwIdle))
					m, err := u.pc.Read(rb)
					if err != nil {
						mu.Lock()
						// Idle with nothing sent either: the socket is done.
						if ne, ok := err.(net.Error); ok && ne.Timeout() && conns != nil &&
							conns[id] == u && time.Since(u.last) < gwIdle {
							mu.Unlock()
							continue
						}
						if conns != nil && conns[id] == u {
							delete(conns, id)
						}
						mu.Unlock()
						u.pc.Close()
						return
					}
					mu.Lock()
					u.last = time.Now()
					mu.Unlock()
					reply(id, rflags, u.addr, rb[:m])
				}
			}(id, u, flags&gwIPv6)
		}
		u.last = now
		pc := u.pc
		mu.Unlock()
		_, _ = pc.Write(data)
	}
}

