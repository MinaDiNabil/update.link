}

cmd_info() {
  local found=0 u p e s
  while IFS=$'\t' read -r u p e s; do
    [ -n "$u" ] || continue
    found=1
    info_one "$u" "$p" "$e" "$s"
  done < <(if [ -n "${1:-}" ]; then "$BIN" user show "$1"; else "$BIN" user list; fi)
  if [ $found = 0 ]; then
    if [ -n "${1:-}" ]; then echo "no such account: $1" >&2; else echo "no accounts yet: udp add USER PASSWORD [DAYS]"; fi
    return 1
  fi
  echo
}

cmd_list() {
  local u p e s n=0
  printf "${B}%-20s %-20s %-12s %s${N}\n" USER PASSWORD EXPIRES STATE
  while IFS=$'\t' read -r u p e s; do
    [ -n "$u" ] || continue
    n=$((n + 1))
    if [ "$s" = active ]; then s="${G}active${N}"; else s="${R}$s${N}"; fi
    printf "%-20s %-20s %-12s %s\n" "$u" "$p" "$e" "$s"
  done < <("$BIN" user list)
  echo "$n account(s)"
}

cmd_add() {
  [ $# -ge 2 ] || { echo "usage: udp add USER PASSWORD [DAYS]" >&2; return 2; }
  "$BIN" user add "$1" "$2" "${3:-0}" || return 1
  echo "${G}account saved${N}"
  cmd_info "$1"
}

cmd_del() {
  [ $# -ge 1 ] || { echo "usage: udp del USER" >&2; return 2; }
  "$BIN" user del "$1" || return 1
  echo "${G}account deleted${N} (a device still connected with it stays on until it reconnects; 'udp restart' drops it now)"
}

listening() { # is anything bound to UDP port $1?
  ss -Hlun 2>/dev/null | awk '{print $4}' | grep -qE "[:.]$1\$"
}

cmd_status() {
  local svc name port ok=0 state line
  printf "${B}%-22s %-10s %-8s %s${N}\n" SERVER SERVICE LISTENS CLIENT-PORTS
  while read -r svc name port; do
    state=$(systemctl is-active "$svc" 2>/dev/null)
    if [ "$state" = active ] && listening "$port"; then
      line="${G}running${N}   "
    else
      line="${R}${state:-down}${N}  "
      ok=1
    fi
    printf "%-22s %b %-8s %s\n" "$name" "$line" "$port" "$CLIENT_PORTS"
  done <<EOF
mina-udp-hysteria Hysteria/SlowUDP $HYSTERIA_PORT
mina-udp-custom UDP-Custom $CUSTOM_PORT
mina-udp-zivpn ZIVPN $ZIVPN_PORT
mina-udp-request UDP-Request $FRONT_PORT
EOF
  if [ "$(systemctl is-active mina-udp-udpgw 2> /dev/null)" = active ] &&
    ss -Hltn 2> /dev/null | awk '{print $4}' | grep -qxF "$UDPGW_ADDR"; then
    echo "udpgw                  ${G}running${N}    $UDPGW_ADDR"
  else
    echo "udpgw                  ${R}down${N}       $UDPGW_ADDR"
    ok=1
  fi
  if "$LIB/firewall.sh" status > /dev/null 2>&1; then
    echo "firewall rules         ${G}in place${N}"
  else
    echo "firewall rules         ${R}missing${N} (udp restart restores them)"
    ok=1
  fi
  echo "address                $PUBLIC_HOST"
  return $ok
}

cmd_restart() {
  systemctl restart mina-udp-firewall $SERVICES
  sleep 2
  cmd_status
}

cmd_logs() {
  case "${1:-}" in
    hysteria | custom | zivpn | request | udpgw | firewall) journalctl -u "mina-udp-$1" -n 50 -f ;;
    "") journalctl -u 'mina-udp-*' -n 50 -f ;;
    *) echo "usage: udp logs [hysteria|custom|zivpn|request]" >&2; return 2 ;;
  esac
}

cmd_uninstall() {
  if [ "${1:-}" != "-y" ]; then
    read -r -p "Remove the UDP servers, their accounts and settings? [y/N] " a
    case "$a" in y | Y | yes) ;; *) echo "kept"; return 0 ;; esac
  fi
  systemctl disable --now mina-udp-firewall $SERVICES > /dev/null 2>&1
  "$LIB/firewall.sh" stop
  rm -f /etc/systemd/system/mina-udp-*.service
  systemctl daemon-reload
  rm -f /etc/sysctl.d/99-mina-udp.conf /etc/modules-load.d/mina-udp.conf
  sysctl --system > /dev/null 2>&1
  rm -f /usr/local/bin/mina-udp /usr/local/bin/mina-udp-auth /usr/local/bin/mina-hysteria \
    /usr/local/bin/mina-udp-custom /usr/local/bin/mina-zivpn
  rm -rf /etc/mina-udp /run/mina-udp "$LIB"
  rm -f /usr/local/bin/udp
  echo "removed"
}

ask() { # ask PROMPT -> $REPLY
  read -r -p "$1" REPLY || exit 0
