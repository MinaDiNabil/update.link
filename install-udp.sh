// allocIP returns a free address of the pool. Called with s.mu held.
func (s *requestServer) allocIP(now time.Time) (netip.Addr, bool) {
	ip := s.nextIP
	for i := 0; i < 1<<(32-s.prefix.Bits()); i++ {
		ip = ip.Next()
		if !s.prefix.Contains(ip) || ip == broadcastOf(s.prefix) {
			ip = s.gateway.Next()
		}
		if _, used := s.byIP[ip]; used {
			continue
		}
		if l, ok := s.leases[ip]; ok && now.Before(l.until) {
			continue
		}
		s.nextIP = ip
		return ip, true
	}
	return netip.Addr{}, false
}

func broadcastOf(p netip.Prefix) netip.Addr {
	a := p.Masked().Addr().As4()
	n := binary.BigEndian.Uint32(a[:]) | (1<<(32-p.Bits()) - 1)
	binary.BigEndian.PutUint32(a[:], n)
	return netip.AddrFrom4(a)
}

func (s *requestServer) usable(ip netip.Addr) bool {
	return ip.Is4() && s.prefix.Contains(ip) && ip != s.gateway &&
		ip != s.prefix.Masked().Addr() && ip != broadcastOf(s.prefix)
}

// enqueue adds a message for the client. Called with c.mu held.
func (c *session) enqueue(m []byte) {
	if len(c.queue) >= maxQueue {
		return
	}
	c.queue = append(c.queue, m)
}

// flush sends what is queued through the open slots. Called with c.mu held.
func (s *requestServer) flush(c *session) {
	for len(c.queue) > 0 && len(c.slots) > 0 {
		sl := c.slots[0]
		c.slots = c.slots[1:]
		buf := make([]byte, 0, s.maxAnswer)
		n := 0
		for n < len(c.queue) {
			m := c.queue[n]
			if n > 0 && len(buf)+2+len(m) > s.maxAnswer {
				break
			}
			buf = binary.BigEndian.AppendUint16(buf, uint16(len(m)))
			buf = append(buf, m...)
			n++
		}
		c.queue = c.queue[n:]
		sendTo(sl.fd, buf, sl.addr)
	}
	if len(c.queue) == 0 {
		c.queue = nil
	}
}

func isHello(m []byte) bool {
	return len(m) >= 10 && len(m) <= 64 && m[len(m)-1] == msgHelloSuffix
}

func (s *requestServer) handleDatagram(d []byte, from netip.AddrPort, fd int) {
	if len(d) < clientIDLen+1 {
		return
	}
	var cid [clientIDLen]byte
	copy(cid[:], d)
	counter := int(d[clientIDLen])
	if counter == 0 {
		counter = 1
	}
	var msgs [][]byte
	for rest := d[clientIDLen+1:]; len(rest) >= 2; {
		l := int(binary.BigEndian.Uint16(rest))
		if len(rest) < 2+l {
			break
		}
		msgs = append(msgs, rest[2:2+l])
		rest = rest[2+l:]
	}

	now := time.Now()
	s.mu.RLock()
	c := s.sessions[cid]
	s.mu.RUnlock()
	if c == nil {
		// Only a hello starts a session; anything else is a poll for one
		// that is gone, which the client notices by its pings going
		// unanswered.
		hello := false
		for _, m := range msgs {
			hello = hello || isHello(m)
		}
		if !hello {
			return
		}
		s.mu.Lock()
		if c = s.sessions[cid]; c == nil {
			if len(s.sessions) >= maxPending+len(s.byIP) {
				s.mu.Unlock()
				return
			}
			c = &session{cid: cid, lastSeen: now}
			s.sessions[cid] = c
		}
		s.mu.Unlock()
	}

	c.mu.Lock()
	defer c.mu.Unlock()
	for i := 0; i < counter; i++ {
		c.slots = append(c.slots, slot{fd, from, now})
	}
	if over := len(c.slots) - maxSlots; over > 0 {
		c.slots = c.slots[over:]
	}
	for _, m := range msgs {
		s.handleMessage(c, m, now)
	}
	s.flush(c)
}

// handleMessage is called with c.mu held.
func (s *requestServer) handleMessage(c *session, m []byte, now time.Time) {
	if c.crypt != nil && c.ip.IsValid() {
		p := c.crypt.decrypt(m)
		if bytes.Equal(p, pingMsg) {
			c.lastSeen = now
			c.enqueue(c.crypt.encrypt(pongMsg))
			return
		}
		if len(p) >= 20 && p[0]>>4 == 4 && int(binary.BigEndian.Uint16(p[2:4])) == len(p) {
			// Only the address this session was given may be the source.
			if src := netip.AddrFrom4([4]byte(p[12:16])); src == c.ip {
				c.lastSeen = now
				_, _ = s.tun.Write(p)
			}
			return
		}
		// Neither: a handshake message repeated because its answer was
		// lost, handled below.
	}
	switch {
	case isHello(m):
		for _, q := range c.queue {
			if bytes.Equal(q, s.pubMsg) {
				return
			}
		}
		c.enqueue(s.pubMsg)
	case len(m) > 3 && m[len(m)-1] == msgAuthSuffix:
		s.handleAuth(c, m, now)
	}
}

// handleAuth is called with c.mu held.
func (s *requestServer) handleAuth(c *session, m []byte, now time.Time) {
	kl := int(binary.BigEndian.Uint16(m))
	if kl == 0 || len(m) < 2+kl+2 {
		return
	}
	key, err := rsa.DecryptOAEP(sha256.New(), nil, s.key, m[2:2+kl], nil)
	if err != nil || (len(key) != 16 && len(key) != 24 && len(key) != 32) {
		return
	}
	block, err := aes.NewCipher(key)
	if err != nil {
		return
	}
	crypt := &cfbCrypt{block}
	var req RequestAuth
	if err := gob.NewDecoder(bytes.NewReader(crypt.decrypt(m[2+kl : len(m)-1]))).Decode(&req); err != nil {
		return
	}
	reply := func(r *ResponseAuth) {
		var b bytes.Buffer
		if err := gob.NewEncoder(&b).Encode(r); err != nil {
			return
		}
		c.enqueue(crypt.encrypt(b.Bytes()))
	}
	accounts, err := loadAccounts(s.users)
	if err != nil {
		log.Printf("accounts: %v", err)
	}
	if !checkUserPass(accounts, req.Username, req.Password, now) {
		log.Printf("login rejected: %q", req.Username)
		reply(&ResponseAuth{})
		return
	}

	if !c.ip.IsValid() {
		s.mu.Lock()
		var ip netip.Addr
		// The address the client had before, when it is still its own: a
		// session of the same account (which this one replaces), a lease
		// kept for it, or simply free.
		if want, ok := netip.AddrFromSlice(req.LocalIP); ok && s.usable(want.Unmap()) {
			want = want.Unmap()
			old := s.byIP[want]
			l, leased := s.leases[want]
			switch {
			case old != nil:
				if old.user == req.Username && bytes.Equal(old.cookie, req.Cookie) && len(req.Cookie) > 0 {
					delete(s.sessions, old.cid)
					ip = want
				}
			case leased && now.Before(l.until):
				if l.user == req.Username {
					ip = want
				}
			default:
				ip = want
			}
		}
		if !ip.IsValid() {
			var ok bool
			if ip, ok = s.allocIP(now); !ok {
				s.mu.Unlock()
				log.Printf("address pool exhausted")
				reply(&ResponseAuth{})
				return
			}
		}
		delete(s.leases, ip)
		c.ip = ip
		c.user = req.Username
		c.cookie = make([]byte, 16)
		_, _ = rand.Read(c.cookie)
		s.byIP[ip] = c
		s.mu.Unlock()
		log.Printf("login: %s -> %s", c.user, ip)
	}
	c.crypt = crypt
	c.key = key
	c.lastSeen = now
	ip4 := c.ip.As4()
	reply(&ResponseAuth{Status: true, IP: ip4[:], Cooke: c.cookie})
}

// --- sockets ---------------------------------------------------------------

// sendTo never blocks: with the socket's buffer full the datagram is dropped,
// as the network would.
func sendTo(fd int, b []byte, to netip.AddrPort) {
	_ = syscall.Sendto(fd, b, 0, &syscall.SockaddrInet4{Port: int(to.Port()), Addr: to.Addr().As4()})
}

// parsePorts turns "1-1023" minus the comma list exclude into port numbers.
func parsePorts(spec, exclude string) ([]int, error) {
	skip := map[int]bool{}
	for _, f := range strings.Split(exclude, ",") {
		if f = strings.TrimSpace(f); f != "" {
			p, err := strconv.Atoi(f)
			if err != nil {
				return nil, fmt.Errorf("bad port %q", f)
			}
			skip[p] = true
		}
	}
	var out []int
	for _, f := range strings.Split(spec, ",") {
		f = strings.TrimSpace(f)
		if f == "" {
			continue
		}
		lo, hi, isRange := strings.Cut(f, "-")
		a, err := strconv.Atoi(lo)
		b := a
		if err == nil && isRange {
			b, err = strconv.Atoi(hi)
		}
		if err != nil || a < 1 || b > 65535 || a > b {
			return nil, fmt.Errorf("bad port range %q", f)
		}
		for p := a; p <= b; p++ {
			if !skip[p] {
				out = append(out, p)
			}
		}
	}
	if len(out) == 0 {
		return nil, errors.New("no ports")
	}
	return out, nil
}

// listenPorts binds a socket to each port and registers it with epoll. A
// port something else on the machine already holds is skipped: datagrams a
// client sends there are lost like any other lost datagram.
func listenPorts(ports []int) (epfd int, bound int, busy []int, err error) {
	epfd, err = syscall.EpollCreate1(syscall.EPOLL_CLOEXEC)
	if err != nil {
		return 0, 0, nil, err
	}
	for _, p := range ports {
		fd, err := syscall.Socket(syscall.AF_INET, syscall.SOCK_DGRAM|syscall.SOCK_NONBLOCK|syscall.SOCK_CLOEXEC, 0)
		if err != nil {
			return 0, 0, nil, fmt.Errorf("socket: %w (is LimitNOFILE high enough?)", err)
		}
		if err := syscall.Bind(fd, &syscall.SockaddrInet4{Port: p}); err != nil {
			syscall.Close(fd)
			busy = append(busy, p)
			continue
		}
		ev := syscall.EpollEvent{Events: syscall.EPOLLIN, Fd: int32(fd)}
		if err := syscall.EpollCtl(epfd, syscall.EPOLL_CTL_ADD, fd, &ev); err != nil {
			return 0, 0, nil, err
		}
		bound++
	}
	return epfd, bound, busy, nil
}

// udpLoop reads every socket from this one goroutine, so a client's
// packets reach the tun device in the order they arrived.
func (s *requestServer) udpLoop() {
	events := make([]syscall.EpollEvent, 256)
	buf := make([]byte, 65535)
	for {
		n, err := syscall.EpollWait(s.epfd, events, -1)
		if err != nil {
			if err == syscall.EINTR {
				continue
			}
			log.Printf("epoll: %v", err)
			return
		}
		for _, ev := range events[:n] {
			fd := int(ev.Fd)
			// A bounded burst per socket, so one busy port cannot starve the rest.
			for i := 0; i < 64; i++ {
				l, from, err := syscall.Recvfrom(fd, buf, 0)
				if err != nil {
					break
				}
				if sa, ok := from.(*syscall.SockaddrInet4); ok {
					s.handleDatagram(buf[:l], netip.AddrPortFrom(netip.AddrFrom4(sa.Addr), uint16(sa.Port)), fd)
				}
			}
		}
	}
}

func (s *requestServer) tunLoop() {
	buf := make([]byte, 65535)
	for {
		n, err := s.tun.Read(buf)
		if err != nil {
			if errors.Is(err, os.ErrClosed) {
				return
			}
			continue
		}
		if n < 20 || buf[0]>>4 != 4 {
			continue
		}
		dst := netip.AddrFrom4([4]byte(buf[16:20]))
		s.mu.RLock()
		c := s.byIP[dst]
		s.mu.RUnlock()
		if c == nil {
			continue
		}
		c.mu.Lock()
		if c.crypt != nil {
			c.enqueue(c.crypt.encrypt(buf[:n]))
			s.flush(c)
		}
		c.mu.Unlock()
	}
}

// housekeeping closes slots that came due and drops sessions gone quiet.
func (s *requestServer) housekeeping() {
	tick := time.NewTicker(100 * time.Millisecond)
	defer tick.Stop()
	var list []*session
	var lastSweep time.Time
	for now := range tick.C {
		list = list[:0]
		s.mu.RLock()
		for _, c := range s.sessions {
			list = append(list, c)
		}
		s.mu.RUnlock()
		due := now.Add(-slotLifetime)
		sweep := now.Sub(lastSweep) > time.Second
		var dead []*session
		for _, c := range list {
			c.mu.Lock()
			for len(c.slots) > 0 && c.slots[0].at.Before(due) {
				sendTo(c.slots[0].fd, nil, c.slots[0].addr)
				c.slots = c.slots[1:]
			}
			if sweep {
				idle := sessionIdle
				if !c.ip.IsValid() {
					idle = pendingIdle
				}
				if now.Sub(c.lastSeen) > idle {
					dead = append(dead, c)
				}
			}
			c.mu.Unlock()
		}
		if !sweep {
			continue
		}
		lastSweep = now
		s.mu.Lock()
		for _, c := range dead {
			// ip, user and cookie are only written with s.mu held, so they
			// are read here without c.mu (which handleAuth holds while it
			// waits for s.mu).
			if s.sessions[c.cid] == c {
				delete(s.sessions, c.cid)
			}
			if c.ip.IsValid() && s.byIP[c.ip] == c {
				delete(s.byIP, c.ip)
				s.leases[c.ip] = lease{c.user, c.cookie, now.Add(leaseKept)}
				log.Printf("logout: %s (%s)", c.user, c.ip)
			}
		}
		for ip, l := range s.leases {
			if now.After(l.until) {
				delete(s.leases, ip)
			}
		}
		s.mu.Unlock()
	}
}

// --- saved sessions --------------------------------------------------------

type savedSession struct {
	CID    [clientIDLen]byte
	User   string
	Key    []byte
	IP     [4]byte
	Cookie []byte
}

// saveSessions writes the authenticated sessions to path.
func (s *requestServer) saveSessions(path string) {
	var out []savedSession
	s.mu.RLock()
	for _, c := range s.byIP {
		c.mu.Lock()
		if c.crypt != nil {
			out = append(out, savedSession{c.cid, c.user, c.key, c.ip.As4(), c.cookie})
		}
		c.mu.Unlock()
	}
	s.mu.RUnlock()
	var b bytes.Buffer
	if err := gob.NewEncoder(&b).Encode(out); err != nil {
		return
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, b.Bytes(), 0o600); err == nil {
		_ = os.Rename(tmp, path)
	}
}

// loadSessions restores what saveSessions wrote, unless it is too old for
// any client to still be waiting on.
func (s *requestServer) loadSessions(path string) int {
	st, err := os.Stat(path)
	if err != nil || time.Since(st.ModTime()) > sessionIdle {
		return 0
	}
	f, err := os.Open(path)
	if err != nil {
		return 0
	}
	defer f.Close()
	var in []savedSession
	if err := gob.NewDecoder(f).Decode(&in); err != nil {
		return 0
	}
	now := time.Now()
	n := 0
	for _, v := range in {
		ip := netip.AddrFrom4(v.IP)
		block, err := aes.NewCipher(v.Key)
		if err != nil || !s.usable(ip) || s.byIP[ip] != nil {
			continue
		}
		c := &session{cid: v.CID, user: v.User, key: v.Key, crypt: &cfbCrypt{block}, ip: ip, cookie: v.Cookie, lastSeen: now}
		s.sessions[c.cid] = c
		s.byIP[ip] = c
		n++
	}
	return n
}

func requestCommand(args []string) int {
	fs := flag.NewFlagSet("request", flag.ExitOnError)
	ports := fs.String("ports", "1-1023", "UDP ports to listen on: every port of the range clients send to")
	exclude := fs.String("exclude", "", "ports of that range to leave alone (comma list)")
	tunName := fs.String("tun", "minaudp0", "tun device name")
	network := fs.String("net", "10.66.0.1/16", "tunnel network, the address being the server's")
	mtu := fs.Int("mtu", 1250, "tun MTU (the client's is 1250)")
	users := fs.String("users", usersFile(), "accounts file")
	// 4096 is the protocol's size and what the app's client is paced for: it
	// opens more slots only when answers come back packed. Measured on a
	// 60 ms / 1 % loss link, one client downloads at 30 Mbit/s with 4096 and
	// at 1 Mbit/s with answers kept under the MTU (1400).
	maxAnswer := fs.Int("max-answer", 4096, "largest answer datagram in bytes")
	state := fs.String("state", "", "file the sessions are saved in across restarts (none if empty)")
	_ = fs.Parse(args)

	log.SetFlags(0)
	prefix, err := netip.ParsePrefix(*network)
	if err != nil || !prefix.Addr().Is4() || prefix.Bits() > 30 || prefix.Bits() < 8 {
		log.Printf("bad -net %q", *network)
		return 1
	}
	if *maxAnswer < 1500 {
		*maxAnswer = 1500
	}
	if *maxAnswer > 65000 {
		*maxAnswer = 65000
	}
	portList, err := parsePorts(*ports, *exclude)
	if err != nil {
		log.Printf("-ports: %v", err)
		return 1
	}
	key, err := rsa.GenerateKey(rand.Reader, 1024)
	if err != nil {
		log.Printf("rsa: %v", err)
		return 1
	}
	pub := binary.BigEndian.AppendUint32(nil, uint32(key.E))
	pub = append(pub, key.N.Bytes()...)

	tun, err := openTun(*tunName)
	if err != nil {
		log.Printf("%v", err)
		return 1
	}
	for _, c := range [][]string{
		{"ip", "addr", "replace", prefix.String(), "dev", *tunName},
		{"ip", "link", "set", "dev", *tunName, "mtu", fmt.Sprint(*mtu), "txqueuelen", "5000", "up"},
	} {
		if err := run(c[0], c[1:]...); err != nil {
			log.Printf("%v", err)
			return 1
		}
	}
	epfd, bound, busy, err := listenPorts(portList)
	if err != nil {
		log.Printf("%v", err)
		return 1
	}
	if bound == 0 {
		log.Printf("could not bind any port of %s", *ports)
		return 1
	}
	if len(busy) > 0 {
		log.Printf("%d port(s) in use by something else and skipped: %v", len(busy), busy)
	}

	s := &requestServer{
		epfd: epfd, tun: tun, key: key, pubMsg: pub, users: *users, maxAnswer: *maxAnswer,
		prefix: prefix.Masked(), gateway: prefix.Addr(), nextIP: prefix.Addr(),
		sessions: map[[clientIDLen]byte]*session{},
		byIP:     map[netip.Addr]*session{},
		leases:   map[netip.Addr]lease{},
	}
	restored := 0
	if *state != "" {
		restored = s.loadSessions(*state)
	}
	go s.udpLoop()
	go s.tunLoop()
	go s.housekeeping()
	log.Printf("UDP Request server listening on %d UDP ports of %s, tunnel %s on %s, %d session(s) restored",
		bound, *ports, prefix, *tunName, restored)

	sig := make(chan os.Signal, 1)
	signal.Notify(sig, syscall.SIGINT, syscall.SIGTERM)
	// Saved every few seconds as well as on the way out, so a crash or a
	// kill loses no more than the logins of the last moments.
	save := time.NewTicker(3 * time.Second)
	for {
		select {
		case <-save.C:
			if *state != "" {
				s.saveSessions(*state)
			}
		case <-sig:
			if *state != "" {
				s.saveSessions(*state)
			}
			tun.Close()
			return 0
		}
	}
}
