// runs it as "cmd ADDR AUTH SEND RECV", Hysteria 2 as "cmd ADDR AUTH TX";
// both take exit status 0 as accepted. Hysteria 2 uses the output as the
// client's id, hysteria v1 as the message shown to the client.
func authCommand(args []string) int {
	if len(args) < 2 {
		return 1
	}
	list, err := loadAccounts(usersFile())
	if err != nil {
		return 1
	}
	user, ok := checkAuth(list, args[1], time.Now())
	if !ok {
		return 1
	}
	fmt.Println(user)
	return 0
}
