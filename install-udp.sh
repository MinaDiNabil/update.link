menu() {
  while :; do
    cat <<EOF

${B}${C}  MinaProNet UDP servers${N}   ($PUBLIC_HOST)
  1) Add / update an account
  2) Delete an account
  3) List accounts
  4) Show connection details
  5) Status
  6) Restart the servers
  7) Logs
  8) Uninstall
  0) Exit
EOF
    ask "  Choose: "
    case "$REPLY" in
      1)
        ask "  Username: "; local u=$REPLY
        ask "  Password: "; local p=$REPLY
        ask "  Days until it expires (0 = never) [30]: "
        cmd_add "$u" "$p" "${REPLY:-30}"
        ;;
      2) cmd_list; ask "  Username to delete: "; [ -n "$REPLY" ] && cmd_del "$REPLY" ;;
