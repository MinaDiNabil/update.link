# Percent-encode for a link's query (RFC 3986 unreserved characters stay).
urlencode() {
  local s=$1 out="" c i
  local LC_ALL=C
  for ((i = 0; i < ${#s}; i++)); do
    c=${s:i:1}
    case $c in
      [a-zA-Z0-9.~_-]) out+=$c ;;
      *) out+=$(printf '%%%02X' "'$c") ;;
    esac
  done
  printf '%s' "$out"
}

info_one() { # info_one USER PASS EXPIRY STATE
  local user=$1 pass=$2 expiry=$3 state=$4 color=$G
  [ "$state" = active ] || color=$R
  cat <<EOF

${B}Account: ${C}$user${N}   password: ${C}$pass${N}   expires: $expiry  ${color}[$state]${N}
${B}------------------------------------------------------------------${N}
${B}UDP Hysteria${N}
  Server : $PUBLIC_HOST
  Port   : any, e.g. $HYSTERIA_PORT
  Obfs   : $HYSTERIA_OBFS
  Auth   : $pass

${B}SlowUDP${N} (link)
  hysteria://$PUBLIC_HOST:$CLIENT_PORTS?protocol=udp&auth=$(urlencode "$pass")&obfsParam=$(urlencode "$HYSTERIA_OBFS")&insecure=1&upmbps=50&downmbps=100#$(urlencode "$user")

${B}UDP Custom${N} (config)
  $PUBLIC_HOST:$CLIENT_PORTS@$user:$pass

${B}ZIVPN UDP${N}
  Server   : $PUBLIC_HOST
  Password : $pass

${B}UDP Request${N}
  Server IP : $PUBLIC_HOST
  Username  : $user
  Password  : $pass
  Ports     : Start ${CLIENT_PORTS%-*}  End ${CLIENT_PORTS#*-}   (any narrower range works too)
