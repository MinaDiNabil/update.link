package main

// UDP Request server: the server side of the protocol the app's UDP REQUEST
// mode speaks (native/udprequest/protocol.go has the wire format, read out of
// the newtoolsworks udpServer). A layer-3 tunnel over UDP:
//
//	client -> server   ClientID [8] | Counter u8 | { Len u16 BE | Message }*
//	server -> client   { Len u16 BE | Message }*      (at most maxAnswer bytes)
//
// The server only ever answers: each client datagram opens Counter "answer
// slots" at the address it came from, and a slot is used as soon as there is
// something for that client, or closed with an empty datagram after
// slotLifetime. Messages are hello (-> RSA public key), auth (RSA-OAEP
// wrapped AES key + AES-CFB gob login -> address), then AES-CFB IPv4 packets
// and PING/PONG.
//
// Where this differs from the original server, it is only in what a client
// cannot see:
//
//   - Any UDP port reaches this server (front.go), where the original
//     listens on one port and has iptables REDIRECT a range to it. A client
//     sends each datagram to a random port, so that is a new NAT mapping per
//     datagram, and under load they collide in conntrack and the kernel
//     drops the packets (and fills the table). Here nothing is translated:
//     an answer is written with the port its slot arrived on as its source,
//     and the firewall rules keep these packets out of connection tracking.
//   - Packets are written to the tun device in arrival order from one
//     goroutine (the original's per-message goroutines reorder them and
//     drop beyond five in flight).
//   - Sessions are saved (in /run, so in memory) and picked up again when
//     this server restarts: a client carries on without a new login, and
//     since the kernel keeps the NAT state of its connections, so do they.
//     A client that does log in again gets its old address back.

import (
	"bytes"
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"crypto/rsa"
	"crypto/sha256"
	"encoding/binary"
	"encoding/gob"
	"errors"
	"flag"
	"fmt"
	"log"
	"net/netip"
	"os"
	"os/exec"
	"os/signal"
	"sync"
	"syscall"
	"time"
	"unsafe"
)

const (
	clientIDLen    = 8
	msgHelloSuffix = 0xff
	msgAuthSuffix  = 0xfe

	// A slot is answered, empty if need be, this long after it was opened.
	// The client gives up on one after 1.8 s.
	slotLifetime = 900 * time.Millisecond
	// Slots and packets kept per session; beyond these the oldest slot is
	// closed and new packets are dropped (TCP inside the tunnel backs off).
	maxSlots = 1024
	maxQueue = 1024
	// The client pings every 4 s and declares the session dead after 15 s
	// without an answer.
	sessionIdle = 45 * time.Second
	// Sessions that never got past the handshake.
	pendingIdle = 10 * time.Second
	maxPending  = 8192
	// How long a closed session's address stays reserved for its owner.
	leaseKept = 30 * time.Minute
)

// kcp-go's initialVector: the CFB IV of the protocol, restarted per message.
var cfbIV = []byte{167, 115, 79, 156, 18, 172, 27, 1, 164, 21, 242, 193, 252, 120, 230, 107}

var (
	pingMsg = []byte("PING")
	pongMsg = []byte("PONG")
)

// Matched by gob on field names; "Cooke" is the protocol's spelling.
type RequestAuth struct {
	Username string
	Password string
	Cookie   []byte
	LocalIP  []byte
}

type ResponseAuth struct {
	Status bool
	IP     []byte
	Cooke  []byte
}

type cfbCrypt struct{ block cipher.Block }

func (c *cfbCrypt) encrypt(p []byte) []byte {
	out := make([]byte, len(p))
	cipher.NewCFBEncrypter(c.block, cfbIV).XORKeyStream(out, p)
	return out
}

func (c *cfbCrypt) decrypt(p []byte) []byte {
	out := make([]byte, len(p))
	cipher.NewCFBDecrypter(c.block, cfbIV).XORKeyStream(out, p)
	return out
}

// slot is one answer the server may send: from the address and port the
// client's datagram was sent to, to the address it came from.
type slot struct {
	local netip.AddrPort
	addr  netip.AddrPort
	at    time.Time
}

type session struct {
	mu       sync.Mutex
	cid      [clientIDLen]byte
	user     string
	key      []byte // of crypt, kept to save the session
	crypt    *cfbCrypt
	ip       netip.Addr // invalid until authenticated
	cookie   []byte
	slots    []slot
	queue    [][]byte
	lastSeen time.Time
}

type lease struct {
	user   string
	cookie []byte
	until  time.Time
}

type requestServer struct {
	fd        int // the transparent socket every port arrives on
	out       *rawSender
	front     *front
	tun       *os.File
	key       *rsa.PrivateKey
	pubMsg    []byte
	users     string
	maxAnswer int
	prefix    netip.Prefix
	gateway   netip.Addr

	mu       sync.RWMutex
	sessions map[[clientIDLen]byte]*session
	byIP     map[netip.Addr]*session
	leases   map[netip.Addr]lease
	nextIP   netip.Addr
}

// --- tun -------------------------------------------------------------------

func openTun(name string) (*os.File, error) {
	const (
		tunSetIff = 0x400454ca
		iffTun    = 0x0001
		iffNoPI   = 0x1000
	)
	fd, err := syscall.Open("/dev/net/tun", syscall.O_RDWR|syscall.O_CLOEXEC, 0)
	if err != nil {
		return nil, fmt.Errorf("/dev/net/tun: %w", err)
	}
	var req struct {
		name  [16]byte
		flags uint16
		_     [22]byte
	}
	copy(req.name[:15], name)
	req.flags = iffTun | iffNoPI
	if _, _, e := syscall.Syscall(syscall.SYS_IOCTL, uintptr(fd), tunSetIff, uintptr(unsafe.Pointer(&req))); e != 0 {
		syscall.Close(fd)
		return nil, fmt.Errorf("TUNSETIFF %s: %w", name, e)
	}
	// Non-blocking, so the runtime poller serves it and Close unblocks Read.
	if err := syscall.SetNonblock(fd, true); err != nil {
		syscall.Close(fd)
		return nil, err
	}
	return os.NewFile(uintptr(fd), "/dev/net/tun"), nil
}

