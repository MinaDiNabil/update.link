      *) echo "  ${Y}unknown choice${N}" ;;
    esac
  done
}

case "${1:-}" in
  "") menu ;;
  add) shift; cmd_add "$@" ;;
  del | delete | remove) shift; cmd_del "$@" ;;
  list | ls) cmd_list ;;
  info | show) shift; cmd_info "$@" ;;
  status) cmd_status ;;
  restart) cmd_restart ;;
  logs) shift; cmd_logs "$@" ;;
  uninstall) shift; cmd_uninstall "$@" ;;
  -h | --help | help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//' ;;
  *) echo "unknown command: $1 (try: udp help)" >&2; exit 2 ;;
esac
__MINA_UDP_EOF__
}

# --- checks ------------------------------------------------------------------

preflight() {
  [ "$(id -u)" = 0 ] || die "run as root: sudo bash $0"
  [ -r /etc/os-release ] || die "this is not Ubuntu"
  # shellcheck disable=SC1091
  . /etc/os-release
  case "${ID:-}" in
    ubuntu) ;;
    debian) warn "this installer is tested on Ubuntu; ${PRETTY_NAME:-Debian} is close enough to try" ;;
    *) die "this installer is for Ubuntu (found: ${PRETTY_NAME:-unknown})" ;;
  esac
  command -v systemctl > /dev/null && [ -d /run/systemd/system ] ||
    die "systemd is not running here; the servers are installed as systemd services"
  case "$(uname -m)" in
    x86_64) ARCH=amd64 ;;
    aarch64) ARCH=arm64 ;;
    *) die "unsupported CPU: $(uname -m) (need x86_64 or aarch64)" ;;
  esac
  [ -c /dev/net/tun ] || modprobe tun 2> /dev/null || true
  [ -c /dev/net/tun ] ||
    warn "/dev/net/tun is missing: UDP Request needs it (on an OpenVZ/LXC VPS, enable TUN in the provider's panel)"
}

packages() {
  step "Installing packages"
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq || warn "apt-get update failed; trying with the package lists already here"
  apt-get install -y -qq --no-install-recommends \
    ca-certificates curl git patch openssl iptables iproute2 kmod procps > /dev/null ||
    die "could not install the packages this needs"
}

# --- build -------------------------------------------------------------------

fetch_go() { # fetch_go VERSION -> $BUILD/go-VERSION
  local v=$1 dir=$BUILD/go-$1 tgz=$BUILD/go-$1.tar.gz
  [ -x "$dir/bin/go" ] && return 0
  curl -fsSL --retry 5 --retry-delay 2 -o "$tgz" "https://go.dev/dl/go$v.linux-$ARCH.tar.gz" ||
    die "could not download Go $v"
  echo "${GO_SHA256[$v-$ARCH]}  $tgz" | sha256sum -c --status ||
    die "Go $v download does not match its checksum"
  mkdir -p "$dir"
  tar -xzf "$tgz" -C "$dir" --strip-components=1
  rm -f "$tgz"
}

fetch_source() { # fetch_source DIR COMMIT
  local dir=$1 commit=$2 i
  rm -rf "$dir"
  git init -q "$dir"
  git -C "$dir" remote add origin "$HYSTERIA_REPO"
  for i in 1 2 3 4; do
    git -C "$dir" fetch -q --depth 1 origin "$commit" && break
    [ "$i" = 4 ] && die "could not fetch the hysteria source"
    sleep $((i * 3))
  done
  git -C "$dir" checkout -q FETCH_HEAD
  [ "$(git -C "$dir" rev-parse HEAD)" = "$commit" ] || die "hysteria source is not the pinned revision"
}

gobuild() { # gobuild GOVERSION SRCDIR OUT ARGS...
  local v=$1 src=$2 out=$3
  shift 3
  (
    cd "$src"
    env GOROOT="$BUILD/go-$v" GOTOOLCHAIN=local GOWORK=off CGO_ENABLED=0 \
      GOPATH="$BUILD/gopath" GOCACHE="$BUILD/gocache" GOFLAGS="${LOWMEM:+-p=1}" \
      "$BUILD/go-$v/bin/go" build -trimpath -o "$out" "$@"
  ) > "$BUILD/build.log" 2>&1 || {
    tail -n 30 "$BUILD/build.log" >&2
    die "building $(basename "$out") failed"
  }
}

built() {
  [ "${FORCE_BUILD:-0}" != 1 ] && [ "$(cat "$LIB/build-version" 2> /dev/null)" = "$BUILD_ID" ] &&
    [ -x /usr/local/bin/mina-hysteria ] && [ -x /usr/local/bin/mina-udp-custom ] &&
    [ -x /usr/local/bin/mina-zivpn ] && [ -x /usr/local/bin/mina-udp ]
}

build() {
  BUILD_ID="$VERSION $HYSTERIA_V1_COMMIT $HYSTERIA_V2_COMMIT $SOURCES_ID"
  if built; then
    step "Servers already built"
    return 0
  fi
  step "Building the servers from source (a few minutes)"
  mkdir -p "$BUILD" "$LIB"
  # The Go linker needs about 1 GB; small machines get swap for the build.
  local mem swap="" LOWMEM=""
  mem=$(awk '/MemTotal|SwapTotal/ {s+=$2} END {print int(s/1024)}' /proc/meminfo)
  if [ "$mem" -lt 1900 ]; then
    LOWMEM=1
    swap=$BUILD/swapfile
    if fallocate -l 2G "$swap" 2> /dev/null && chmod 600 "$swap" && mkswap -q "$swap" && swapon "$swap" 2> /dev/null; then
      echo "    (${mem} MB of memory: using 2 GB of temporary swap)"
    else
      rm -f "$swap"
      swap=""
      warn "${mem} MB of memory and no swap could be added; the build may run out of memory"
    fi
  fi
  # shellcheck disable=SC2064
  trap "[ -n '$swap' ] && { swapoff '$swap' 2>/dev/null; rm -f '$swap'; }; true" EXIT

  fetch_go "$GO_V1"
  fetch_go "$GO_V2"
  write_sources "$BUILD/src"
  local out=$BUILD/out pkg=github.com/apernet/hysteria/app/v2/cmd
  mkdir -p "$out"

  echo "    hysteria v1 (UDP Hysteria, SlowUDP)"
  fetch_source "$BUILD/hysteria-v1" "$HYSTERIA_V1_COMMIT"
  gobuild "$GO_V1" "$BUILD/hysteria-v1/app" "$out/mina-hysteria" \
    -ldflags "-s -w -X main.appVersion=v1.3.5" ./cmd

  echo "    hysteria v1 + UDP Custom"
  git -C "$BUILD/hysteria-v1" apply "$BUILD/src/patches/hysteria-v1-udpcustom.patch" \
    "$BUILD/src/patches/hysteria-v1-udpcustom-server.patch" || die "UDP Custom patch does not apply"
  gobuild "$GO_V1" "$BUILD/hysteria-v1/app" "$out/mina-udp-custom" \
    -ldflags "-s -w -X main.appVersion=v1.3.5-udpcustom" ./cmd

  echo "    Hysteria 2 + ZIVPN"
  fetch_source "$BUILD/hysteria-v2" "$HYSTERIA_V2_COMMIT"
  git -C "$BUILD/hysteria-v2" apply "$BUILD/src/patches/hysteria-v2-zivpn.patch" || die "ZIVPN patch does not apply"
  gobuild "$GO_V2" "$BUILD/hysteria-v2/app" "$out/mina-zivpn" \
    -ldflags "-s -w -X $pkg.appVersion=v2.6.0-zivpn -X $pkg.appType=release" .

  echo "    mina-udp (UDP Request, accounts)"
  gobuild "$GO_V2" "$BUILD/src/minaudp" "$out/mina-udp" -ldflags "-s -w" .

  # Renamed into place, so a running server keeps its old file until restarted.
  local b
  for b in mina-hysteria mina-udp-custom mina-zivpn mina-udp; do
    install -m 755 "$out/$b" "/usr/local/bin/.$b.new"
    mv -f "/usr/local/bin/.$b.new" "/usr/local/bin/$b"
  done
  ln -sfn mina-udp /usr/local/bin/mina-udp-auth
  echo "$BUILD_ID" > "$LIB/build-version"

  if [ -n "$swap" ]; then
    swapoff "$swap" 2> /dev/null || true
    rm -f "$swap"
  fi
  trap - EXIT
  # go's module cache is read-only.
  chmod -R u+w "$BUILD" 2> /dev/null || true
  rm -rf "$BUILD"
}

# --- configuration -----------------------------------------------------------

public_ip() {
  local ip url
  for url in https://api.ipify.org https://ipv4.icanhazip.com https://ifconfig.me/ip; do
    ip=$(curl -4 -fsS -m 8 "$url" 2> /dev/null | tr -d '[:space:]') || true
    if [[ "$ip" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
      echo "$ip"
      return
    fi
  done
  ip -4 route get 1.1.1.1 2> /dev/null | sed -n 's/.* src \([0-9.]*\).*/\1/p' | head -n 1
}

random() { # random LENGTH: letters and digits
  local s=""
  while [ ${#s} -lt "$1" ]; do
    s+=$(head -c 64 /dev/urandom | LC_ALL=C tr -dc 'a-zA-Z0-9') || true
  done
  echo "${s:0:$1}"
}

valid_ports() { # every item of a comma list is a port number
  local p
  for p in ${1//,/ }; do
    [[ "$p" =~ ^[0-9]+$ ]] && [ "$p" -ge 1 ] && [ "$p" -le 65535 ] || return 1
  done
}

# The widest run of ports in REQUEST_RANGE that holds no excluded port: the
# range to type into the app, where every port then reaches the server.
request_hint() {
  local lo=${REQUEST_RANGE%-*} hi=${REQUEST_RANGE#*-} p start best_lo best_hi
  start=$lo best_lo=$lo best_hi=$lo
  for p in $(echo "$UDP_EXCLUDE" | tr ',' '\n' | sort -n | uniq) $((hi + 1)); do
    [ "$p" -ge "$lo" ] && [ "$p" -le $((hi + 1)) ] || continue
    if [ $((p - 1 - start)) -gt $((best_hi - best_lo)) ]; then
      best_lo=$start best_hi=$((p - 1))
    fi
    start=$((p + 1))
  done
  echo "$best_lo-$best_hi"
}

configure() {
  step "Writing the configuration"
  mkdir -p "$ETC" "$LIB"
  chmod 700 "$ETC"

  # Values of an earlier install win over the defaults, so re-running this
  # never changes what clients already have typed in.
  local old_host="" old_obfs="" old_exclude=""
  if [ -r "$CONF" ]; then
    old_host=$(. "$CONF" && echo "${PUBLIC_HOST:-}")
    old_obfs=$(. "$CONF" && echo "${HYSTERIA_OBFS:-}")
    old_exclude=$(. "$CONF" && echo "${UDP_EXCLUDE:-}")
  fi
  PUBLIC_HOST=${UDP_HOST:-${old_host:-$(public_ip)}}
  [ -n "$PUBLIC_HOST" ] || die "could not find this machine's public address; run again with UDP_HOST=<address>"
  HYSTERIA_OBFS=${old_obfs:-$(random 12)}
  UDP_EXCLUDE=${UDP_EXCLUDE:-${old_exclude:-$DEFAULT_EXCLUDE}}
  valid_ports "$UDP_EXCLUDE" || die "UDP_EXCLUDE must be a comma-separated list of ports"
  REQUEST_HINT=$(request_hint)

  cat > "$CONF" <<EOF
# MinaProNet UDP servers. Written by install-udp.sh on every run; to change
# the address or the excluded ports, run it again with UDP_HOST= or
# UDP_EXCLUDE= set.
PUBLIC_HOST='$PUBLIC_HOST'
HYSTERIA_OBFS='$HYSTERIA_OBFS'
UDP_EXCLUDE='$UDP_EXCLUDE'
REQUEST_RANGE=$REQUEST_RANGE
REQUEST_HINT=$REQUEST_HINT
REQUEST_TUN=$REQUEST_TUN
REQUEST_NET=$REQUEST_NET
REQUEST_SUBNET=$REQUEST_SUBNET
ZIVPN_PORT=$ZIVPN_PORT
ZIVPN_RANGE=$ZIVPN_RANGE
HYSTERIA_PORT=$HYSTERIA_PORT
HYSTERIA_RANGE=$HYSTERIA_RANGE
CUSTOM_PORT=$CUSTOM_PORT
CUSTOM_RANGE=$CUSTOM_RANGE
UDPGW_ADDR=$UDPGW_ADDR
EOF
  chmod 600 "$CONF"

  # One self-signed certificate for the three hysteria servers. The app does
  # not verify it (these protocols never do), so it is kept across re-runs.
  if [ ! -s "$ETC/cert.pem" ] || [ ! -s "$ETC/key.pem" ]; then
    openssl req -x509 -newkey rsa:2048 -nodes -sha256 -days 3650 \
      -keyout "$ETC/key.pem" -out "$ETC/cert.pem" -subj "/CN=$PUBLIC_HOST" 2> /dev/null ||
      die "could not create the TLS certificate"
    chmod 600 "$ETC/key.pem"
  fi

  cat > "$ETC/hysteria.json" <<EOF
{
  "listen": ":$HYSTERIA_PORT",
  "cert": "$ETC/cert.pem",
  "key": "$ETC/key.pem",
  "obfs": "$HYSTERIA_OBFS",
  "auth": {"mode": "external", "config": {"cmd": "/usr/local/bin/mina-udp-auth"}},
  "recv_window_conn": 16777216,
  "recv_window_client": 67108864,
  "max_conn_client": 4096
}
EOF
  cat > "$ETC/udp-custom.json" <<EOF
{
  "listen": ":$CUSTOM_PORT",
  "cert": "$ETC/cert.pem",
  "key": "$ETC/key.pem",
  "obfs": "$CUSTOM_OBFS",
  "alpn": "h3",
  "auth": {"mode": "external", "config": {"cmd": "/usr/local/bin/mina-udp-auth"}},
  "recv_window_conn": 16777216,
  "recv_window_client": 67108864,
  "max_conn_client": 4096
}
EOF
  cat > "$ETC/zivpn.yaml" <<EOF
listen: :$ZIVPN_PORT
tls:
  cert: $ETC/cert.pem
  key: $ETC/key.pem
obfs:
  type: salamander
  salamander:
    password: '$ZIVPN_OBFS'
auth:
  type: command
  command: /usr/local/bin/mina-udp-auth
quic:
  initStreamReceiveWindow: 8388608
  maxStreamReceiveWindow: 8388608
  initConnReceiveWindow: 20971520
  maxConnReceiveWindow: 20971520
  maxIdleTimeout: 60s
  maxIncomingStreams: 1024
udpIdleTimeout: 120s
EOF
  chmod 600 "$ETC"/*.json "$ETC"/*.yaml

  write_tools "$LIB"
  chmod 755 "$LIB/firewall.sh" "$LIB/udp.sh"
  ln -sfn "$LIB/udp.sh" /usr/local/bin/udp
}

tune() {
  step "Tuning the kernel for UDP throughput"
  local bbr=""
  modprobe tcp_bbr 2> /dev/null || true
  modprobe nf_conntrack 2> /dev/null || true
  if grep -qw bbr /proc/sys/net/ipv4/tcp_available_congestion_control 2> /dev/null; then
    bbr="net.core.default_qdisc = fq
net.ipv4.tcp_congestion_control = bbr"
  fi
  cat > /etc/sysctl.d/99-mina-udp.conf <<EOF
# MinaProNet UDP servers (install-udp.sh).
net.ipv4.ip_forward = 1
# QUIC wants large socket buffers; the default 208 KB cap throttles it and
# drops packets under load.
net.core.rmem_max = 33554432
net.core.wmem_max = 33554432
net.core.rmem_default = 1048576
net.core.wmem_default = 1048576
net.core.netdev_max_backlog = 16384
net.core.somaxconn = 8192
net.ipv4.udp_rmem_min = 16384
net.ipv4.udp_wmem_min = 16384
# The servers' own outgoing connections stay clear of the client port ranges.
net.ipv4.ip_local_port_range = 40000 65535
# Outgoing TCP (what the tunnels fetch for their clients).
net.ipv4.tcp_fastopen = 3
net.ipv4.tcp_mtu_probing = 1
net.ipv4.tcp_slow_start_after_idle = 0
net.ipv4.tcp_rmem = 4096 131072 33554432
net.ipv4.tcp_wmem = 4096 65536 33554432
$bbr
# Every client is a few conntrack entries (port hopping makes more); a full
# table drops packets.
net.netfilter.nf_conntrack_max = 1048576
net.netfilter.nf_conntrack_udp_timeout = 60
net.netfilter.nf_conntrack_udp_timeout_stream = 180
EOF
  printf 'tun\nnf_conntrack\n%s' "${bbr:+tcp_bbr
}" > /etc/modules-load.d/mina-udp.conf
  chmod 644 /etc/sysctl.d/99-mina-udp.conf /etc/modules-load.d/mina-udp.conf
  # -e: a key this kernel lacks (containers, old kernels) is skipped.
  sysctl -e -q -p /etc/sysctl.d/99-mina-udp.conf > /dev/null 2>&1 || true
}

