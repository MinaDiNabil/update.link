# start_service NAME FILE...: (re)start the service only if one of the files
# it runs from changed since it was last started by this installer. Running
# the installer again with nothing new then leaves every client connected.
start_service() {
  local name=$1 stamp=$LIB/stamp-$1 sum
  shift
  sum=$(cat "/etc/systemd/system/$name.service" "$@" 2> /dev/null | sha256sum)
  if [ "$sum" = "$(cat "$stamp" 2> /dev/null)" ] && systemctl -q is-active "$name"; then
    return 0
  fi
  systemctl restart "$name"
  echo "$sum" > "$stamp"
}

services() {
  step "Installing the services"
  unit mina-udp-hysteria "hysteria v1 (UDP Hysteria, SlowUDP)" \
    "/usr/local/bin/mina-hysteria --no-check --log-level info server --config $ETC/hysteria.json"
  unit mina-udp-custom "UDP Custom" \
    "/usr/local/bin/mina-udp-custom --no-check --log-level info server --config $ETC/udp-custom.json"
  unit mina-udp-zivpn "ZIVPN UDP" \
    "/usr/local/bin/mina-zivpn server --disable-update-check --log-level info --config $ETC/zivpn.yaml" \
    "Environment=HYSTERIA_DISABLE_UPDATE_CHECK=1"
  unit mina-udp-request "UDP Request" \
    "/usr/local/bin/mina-udp request -ports $REQUEST_RANGE -exclude $UDP_EXCLUDE,$ZIVPN_PORT,$HYSTERIA_PORT,$CUSTOM_PORT -tun $REQUEST_TUN -net $REQUEST_NET -users $ETC/users.db -state /run/mina-udp/sessions" \
    "ExecStartPre=-/sbin/modprobe tun
RuntimeDirectory=mina-udp
RuntimeDirectoryMode=0700
RuntimeDirectoryPreserve=yes"
  unit mina-udp-udpgw "udpgw (UDP traffic of the hysteria modes)" \
    "/usr/local/bin/mina-udp udpgw -listen $UDPGW_ADDR"

  # Stays running: other tools (ufw, docker, an iptables-restore) can flush
  # rules at any time, and this puts them back within seconds.
  cat > /etc/systemd/system/mina-udp-firewall.service <<EOF
[Unit]
Description=MinaProNet UDP: firewall rules
After=network-pre.target
Wants=network-pre.target
StartLimitIntervalSec=0

[Service]
Type=simple
ExecStart=$LIB/firewall.sh watch
ExecStopPost=$LIB/firewall.sh stop
Restart=always
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF
  chmod 644 /etc/systemd/system/mina-udp-firewall.service
  systemctl daemon-reload
  systemctl enable -q mina-udp-firewall.service \
    mina-udp-udpgw mina-udp-hysteria mina-udp-custom mina-udp-zivpn mina-udp-request
  local cert="$ETC/cert.pem $ETC/key.pem" b=/usr/local/bin
  # shellcheck disable=SC2086
  {
    start_service mina-udp-firewall "$LIB/firewall.sh" "$CONF"
    start_service mina-udp-udpgw $b/mina-udp
    start_service mina-udp-hysteria $b/mina-hysteria "$ETC/hysteria.json" $cert
    start_service mina-udp-custom $b/mina-udp-custom "$ETC/udp-custom.json" $cert
    start_service mina-udp-zivpn $b/mina-zivpn "$ETC/zivpn.yaml" $cert
    start_service mina-udp-request $b/mina-udp
  }
}

first_account() {
  # Accounts of an earlier install stay as they are.
  [ -s "$ETC/users.db" ] && return 0
  local user=${UDP_USER:-} pass=${UDP_PASS:-} days=${UDP_DAYS:-}
  if [ -z "$user" ] && [ -t 0 ]; then
    echo
    read -r -p "First account - username [mina]: " user || true
    read -r -p "First account - password [random]: " pass || true
    read -r -p "First account - days until it expires, 0 = never [0]: " days || true
  fi
  user=${user:-mina}
  pass=${pass:-$(random 10)}
  /usr/local/bin/mina-udp user add "$user" "$pass" "${days:-0}" ||
    die "could not create the account (add one with: udp add USER PASSWORD [DAYS])"
}

verify() {
  step "Checking that every server is up"
  local i
  for i in $(seq 1 15); do
    if /usr/local/bin/udp status > /dev/null 2>&1; then
      /usr/local/bin/udp status
      return 0
    fi
    sleep 1
  done
  /usr/local/bin/udp status || true
  die "not every server came up; see: udp logs"
}

install_all() {
  preflight
  packages
  build
  configure
  tune
  first_account
  services
  verify
  /usr/local/bin/udp info || true
  cat <<EOF
${G}${B}Done.${N} The servers start on boot and restart themselves if they ever stop.
Manage accounts with:  ${B}udp${N}   (menu)   or   udp add USER PASSWORD [DAYS]
If your provider has its own firewall (security group), allow ${B}all UDP ports${N} there.
EOF
}

case "${1:-install}" in
  install) install_all ;;
  uninstall)
    [ "$(id -u)" = 0 ] || die "run as root"
    [ -x /usr/local/bin/udp ] || die "not installed"
    shift
    /usr/local/bin/udp uninstall "$@"
    ;;
  -h | --help | help) sed -n '2,38p' "$0" | sed 's/^# \{0,1\}//' ;;
  *) die "unknown command: $1 (install | uninstall)" ;;
esac
