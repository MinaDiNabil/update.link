const defaultUsersFile = "/etc/mina-udp/users.db"

type account struct {
	User    string
	Pass    string
	Expires string // YYYY-MM-DD, or "" for never
}

func (a account) expired(now time.Time) bool {
	if a.Expires == "" {
		return false
	}
	t, err := time.Parse("2006-01-02", a.Expires)
	if err != nil {
		return true
	}
	return !now.UTC().Before(t.Add(24 * time.Hour))
}

func usersFile() string {
	if p := os.Getenv("MINA_UDP_USERS"); p != "" {
		return p
	}
	return defaultUsersFile
}

func loadAccounts(path string) ([]account, error) {
	f, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	defer f.Close()
	var out []account
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		p := strings.Split(line, "\t")
		if len(p) < 2 || p[0] == "" || p[1] == "" {
			continue
		}
		a := account{User: p[0], Pass: p[1]}
		if len(p) > 2 && p[2] != "-" {
			a.Expires = p[2]
		}
		out = append(out, a)
	}
	return out, sc.Err()
}

func saveAccounts(path string, list []account) error {
	sort.Slice(list, func(i, j int) bool { return list[i].User < list[j].User })
	var b strings.Builder
	for _, a := range list {
		exp := a.Expires
		if exp == "" {
			exp = "-"
		}
		fmt.Fprintf(&b, "%s\t%s\t%s\n", a.User, a.Pass, exp)
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(b.String()), 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// withLock runs fn holding an exclusive lock, so two edits cannot interleave.
func withLock(path string, fn func() error) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	l, err := os.OpenFile(path+".lock", os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return err
	}
	defer l.Close()
	if err := syscall.Flock(int(l.Fd()), syscall.LOCK_EX); err != nil {
		return err
	}
	return fn()
}

// checkUserPass is the UDP Request and UDP Custom check: account and password.
func checkUserPass(list []account, user, pass string, now time.Time) bool {
	for _, a := range list {
		if a.User == user {
			return a.Pass == pass && !a.expired(now)
		}
	}
	return false
}

// checkAuth takes the auth string of a hysteria client and returns the
// account it belongs to. UDP Custom sends "user:pass"; ZIVPN sends the
// password alone, and UDP Hysteria / SlowUDP whichever was typed in, so a
// string that is no "user:pass" of ours is tried as a bare password.
func checkAuth(list []account, auth string, now time.Time) (string, bool) {
	if i := strings.IndexByte(auth, ':'); i > 0 {
		if checkUserPass(list, auth[:i], auth[i+1:], now) {
			return auth[:i], true
		}
	}
	for _, a := range list {
		if a.Pass == auth && !a.expired(now) {
			return a.User, true
		}
	}
	return "", false
}

func validName(s string) error {
	if s == "" || len(s) > 64 {
		return errors.New("must be 1-64 characters")
	}
	for _, r := range s {
		if r <= ' ' || r == 0x7f || r == ':' || r == '@' {
			return errors.New("must not contain spaces, ':' or '@'")
		}
	}
	return nil
}

func validPass(s string) error {
	if s == "" || len(s) > 128 {
		return errors.New("must be 1-128 characters")
	}
	for _, r := range s {
		// '#' and '?' would cut a UDP Custom config string short.
		if r <= ' ' || r == 0x7f || r == '#' || r == '?' {
			return errors.New("must not contain spaces, '#' or '?'")
		}
	}
	return nil
}

// userCommand implements "mina-udp user add|del|list|show".
func userCommand(args []string) int {
	path := usersFile()
	fail := func(format string, a ...any) int {
		fmt.Fprintf(os.Stderr, format+"\n", a...)
		return 1
	}
	if len(args) == 0 {
		return fail("usage: user add NAME PASSWORD [DAYS] | del NAME | list | show NAME")
	}
	switch args[0] {
	case "add":
		if len(args) < 3 {
			return fail("usage: user add NAME PASSWORD [DAYS]")
		}
		name, pass := args[1], args[2]
		if err := validName(name); err != nil {
			return fail("username %v", err)
		}
		if err := validPass(pass); err != nil {
			return fail("password %v", err)
		}
		exp := ""
		if len(args) > 3 && args[3] != "" && args[3] != "0" {
			var days int
			if _, err := fmt.Sscanf(args[3], "%d", &days); err != nil || days < 0 || days > 36500 {
				return fail("days must be a number (0 = never expires)")
			}
			if days > 0 {
				// Valid through the end of that day.
				exp = time.Now().UTC().AddDate(0, 0, days).Format("2006-01-02")
			}
		}
		err := withLock(path, func() error {
			list, err := loadAccounts(path)
			if err != nil {
				return err
			}
			// ZIVPN sends the password alone, so two accounts with one
			// password could not be told apart.
			for _, a := range list {
				if a.User != name && a.Pass == pass {
					return fmt.Errorf("another account already uses this password")
				}
			}
			kept := list[:0]
			for _, a := range list {
				if a.User != name {
					kept = append(kept, a)
				}
			}
			return saveAccounts(path, append(kept, account{name, pass, exp}))
		})
		if err != nil {
			return fail("%v", err)
		}
	case "del":
		if len(args) < 2 {
			return fail("usage: user del NAME")
		}
		found := false
		err := withLock(path, func() error {
			list, err := loadAccounts(path)
			if err != nil {
				return err
			}
			kept := list[:0]
			for _, a := range list {
				if a.User == args[1] {
					found = true
					continue
				}
				kept = append(kept, a)
			}
			return saveAccounts(path, kept)
		})
		if err != nil {
			return fail("%v", err)
		}
		if !found {
			return fail("no such account: %s", args[1])
		}
	case "list", "show":
		list, err := loadAccounts(path)
		if err != nil {
			return fail("%v", err)
		}
		now := time.Now()
		found := false
		for _, a := range list {
			if args[0] == "show" && (len(args) < 2 || a.User != args[1]) {
				continue
			}
			found = true
			exp, state := a.Expires, "active"
			if exp == "" {
				exp = "never"
			}
			if a.expired(now) {
				state = "expired"
			}
			fmt.Printf("%s\t%s\t%s\t%s\n", a.User, a.Pass, exp, state)
		}
		if args[0] == "show" && !found {
			return 1
		}
	default:
		return fail("unknown user command %q", args[0])
	}
	return 0
}

