package main

// The one account list every UDP protocol of the server authenticates
// against. One account per line: user TAB password TAB expiry, the expiry a
// YYYY-MM-DD date (the account works through the end of that day, UTC) or
// "-" for none. The file is read on every check, so adding or removing an
// account never restarts a server or drops the people connected to it.

