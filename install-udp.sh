# --- build -------------------------------------------------------------------

fetch_go() { # fetch_go VERSION -> $BUILD/go-VERSION
  local v=$1 dir=$BUILD/go-$1 tgz=$BUILD/go-$1.tar.gz
  [ -x "$dir/bin/go" ] && return 0
  # go.dev is not reachable (or answers 404) from every network; the mirrors
  # serve the same file, and the checksum below is what is trusted.
  local f=go$v.linux-$ARCH.tar.gz url ok=""
  for url in "https://go.dev/dl/$f" "https://dl.google.com/go/$f" \
    "https://golang.google.cn/dl/$f" "https://mirrors.aliyun.com/golang/$f"; do
    if curl -fsSL --retry 2 --retry-delay 2 --connect-timeout 15 -o "$tgz" "$url" 2> /dev/null &&
      echo "${GO_SHA256[$v-$ARCH]}  $tgz" | sha256sum -c --status; then
      ok=1
      break
    fi
    echo "    (Go $v: ${url%/"$f"} did not work, trying the next source)"
  done
  [ -n "$ok" ] || die "could not download Go $v from go.dev or its mirrors (is outbound HTTPS open on this server?)"
  mkdir -p "$dir"
  tar -xzf "$tgz" -C "$dir" --strip-components=1
  rm -f "$tgz"
}

fetch_source() { # fetch_source DIR COMMIT
  local dir=$1 commit=$2 i
  rm -rf "$dir"
  git init -q "$dir"
  git -C "$dir" remote add origin "$HYSTERIA_REPO"
  for i in 1 2 3 4; do
    git -C "$dir" fetch -q --depth 1 origin "$commit" && break
    [ "$i" = 4 ] && die "could not fetch the hysteria source"
    sleep $((i * 3))
  done
  git -C "$dir" checkout -q FETCH_HEAD
  [ "$(git -C "$dir" rev-parse HEAD)" = "$commit" ] || die "hysteria source is not the pinned revision"
}

# Modules come from the first proxy that answers; each is checked against
# the hashes in the source's own go.sum, so no checksum database is asked.
gobuild() { # gobuild GOVERSION SRCDIR OUT ARGS...
  local v=$1 src=$2 out=$3
  shift 3
  (
    cd "$src"
    env GOROOT="$BUILD/go-$v" GOTOOLCHAIN=local GOWORK=off CGO_ENABLED=0 \
      GOPATH="$BUILD/gopath" GOCACHE="$BUILD/gocache" GOFLAGS="${LOWMEM:+-p=1}" \
      GOPROXY="https://proxy.golang.org|https://goproxy.io|https://goproxy.cn|direct" GOSUMDB=off \
      "$BUILD/go-$v/bin/go" build -trimpath -o "$out" "$@"
  ) > "$BUILD/build.log" 2>&1 || {
    tail -n 30 "$BUILD/build.log" >&2
    die "building $(basename "$out") failed"
  }
}

built() {
  [ "${FORCE_BUILD:-0}" != 1 ] && [ "$(cat "$LIB/build-version" 2> /dev/null)" = "$BUILD_ID" ] &&
    [ -x /usr/local/bin/mina-hysteria ] && [ -x /usr/local/bin/mina-udp-custom ] &&
    [ -x /usr/local/bin/mina-zivpn ] && [ -x /usr/local/bin/mina-udp ]
}

build() {
  BUILD_ID="$VERSION $HYSTERIA_V1_COMMIT $HYSTERIA_V2_COMMIT $SOURCES_ID"
  if built; then
    step "Servers already built"
    return 0
  fi
  step "Building the servers from source (a few minutes)"
  mkdir -p "$BUILD" "$LIB"
  # The Go linker needs about 1 GB; small machines get swap for the build.
  local mem swap="" LOWMEM=""
  mem=$(awk '/MemTotal|SwapTotal/ {s+=$2} END {print int(s/1024)}' /proc/meminfo)
  if [ "$mem" -lt 1900 ]; then
    LOWMEM=1
    swap=$BUILD/swapfile
    if fallocate -l 2G "$swap" 2> /dev/null && chmod 600 "$swap" && mkswap -q "$swap" && swapon "$swap" 2> /dev/null; then
      echo "    (${mem} MB of memory: using 2 GB of temporary swap)"
    else
      rm -f "$swap"
      swap=""
      warn "${mem} MB of memory and no swap could be added; the build may run out of memory"
    fi
  fi
  # shellcheck disable=SC2064
  trap "[ -n '$swap' ] && { swapoff '$swap' 2>/dev/null; rm -f '$swap'; }; true" EXIT

  fetch_go "$GO_V1"
  fetch_go "$GO_V2"
  write_sources "$BUILD/src"
  local out=$BUILD/out pkg=github.com/apernet/hysteria/app/v2/cmd
  mkdir -p "$out"

  echo "    hysteria v1 (UDP Hysteria, SlowUDP)"
  fetch_source "$BUILD/hysteria-v1" "$HYSTERIA_V1_COMMIT"
  gobuild "$GO_V1" "$BUILD/hysteria-v1/app" "$out/mina-hysteria" \
    -ldflags "-s -w -X main.appVersion=v1.3.5" ./cmd

  echo "    hysteria v1 + UDP Custom"
  git -C "$BUILD/hysteria-v1" apply "$BUILD/src/patches/hysteria-v1-udpcustom.patch" \
    "$BUILD/src/patches/hysteria-v1-udpcustom-server.patch" || die "UDP Custom patch does not apply"
  gobuild "$GO_V1" "$BUILD/hysteria-v1/app" "$out/mina-udp-custom" \
    -ldflags "-s -w -X main.appVersion=v1.3.5-udpcustom" ./cmd

  echo "    Hysteria 2 + ZIVPN"
  fetch_source "$BUILD/hysteria-v2" "$HYSTERIA_V2_COMMIT"
  git -C "$BUILD/hysteria-v2" apply "$BUILD/src/patches/hysteria-v2-zivpn.patch" || die "ZIVPN patch does not apply"
  gobuild "$GO_V2" "$BUILD/hysteria-v2/app" "$out/mina-zivpn" \
    -ldflags "-s -w -X $pkg.appVersion=v2.6.0-zivpn -X $pkg.appType=release" .

  echo "    mina-udp (UDP Request, accounts)"
  gobuild "$GO_V2" "$BUILD/src/minaudp" "$out/mina-udp" -ldflags "-s -w" .

  # Renamed into place, so a running server keeps its old file until restarted.
  local b
  for b in mina-hysteria mina-udp-custom mina-zivpn mina-udp; do
    install -m 755 "$out/$b" "/usr/local/bin/.$b.new"
    mv -f "/usr/local/bin/.$b.new" "/usr/local/bin/$b"
  done
  ln -sfn mina-udp /usr/local/bin/mina-udp-auth
  echo "$BUILD_ID" > "$LIB/build-version"

  if [ -n "$swap" ]; then
    swapoff "$swap" 2> /dev/null || true
    rm -f "$swap"
  fi
  trap - EXIT
  # go's module cache is read-only.
  chmod -R u+w "$BUILD" 2> /dev/null || true
  rm -rf "$BUILD"
}

# --- configuration -----------------------------------------------------------

public_ip() {
  local ip url
  for url in https://api.ipify.org https://ipv4.icanhazip.com https://ifconfig.me/ip; do
    ip=$(curl -4 -fsS -m 8 "$url" 2> /dev/null | tr -d '[:space:]') || true
    if [[ "$ip" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
      echo "$ip"
      return
    fi
  done
  ip -4 route get 1.1.1.1 2> /dev/null | sed -n 's/.* src \([0-9.]*\).*/\1/p' | head -n 1
}

random() { # random LENGTH: letters and digits
  local s=""
  while [ ${#s} -lt "$1" ]; do
    s+=$(head -c 64 /dev/urandom | LC_ALL=C tr -dc 'a-zA-Z0-9') || true
  done
  echo "${s:0:$1}"
}

valid_ports() { # every item of a comma list is a port number
  local p
  for p in ${1//,/ }; do
    [[ "$p" =~ ^[0-9]+$ ]] && [ "$p" -ge 1 ] && [ "$p" -le 65535 ] || return 1
  done
}

configure() {
  step "Writing the configuration"
  mkdir -p "$ETC" "$LIB"
  chmod 700 "$ETC"

  # Values of an earlier install win over the defaults, so re-running this
  # never changes what clients already have typed in.
  local old_host="" old_exclude=""
  if [ -r "$CONF" ]; then
    old_host=$(. "$CONF" && echo "${PUBLIC_HOST:-}")
    old_exclude=$(. "$CONF" && echo "${UDP_EXCLUDE:-}")
  fi
  PUBLIC_HOST=${UDP_HOST:-${old_host:-$(public_ip)}}
  [ -n "$PUBLIC_HOST" ] || die "could not find this machine's public address; run again with UDP_HOST=<address>"
  UDP_EXCLUDE=${UDP_EXCLUDE:-${old_exclude:-$DEFAULT_EXCLUDE}}
  valid_ports "$UDP_EXCLUDE" || die "UDP_EXCLUDE must be a comma-separated list of ports"

  cat > "$CONF" <<EOF
# MinaProNet UDP servers. Written by install-udp.sh on every run; to change
# the address or the excluded ports, run it again with UDP_HOST= or
# UDP_EXCLUDE= set.
PUBLIC_HOST='$PUBLIC_HOST'
HYSTERIA_OBFS='$HYSTERIA_OBFS'
UDP_EXCLUDE='$UDP_EXCLUDE'
CLIENT_PORTS=$CLIENT_PORTS
FRONT_PORT=$FRONT_PORT
FRONT_MARK=$FRONT_MARK
REQUEST_TUN=$REQUEST_TUN
REQUEST_NET=$REQUEST_NET
REQUEST_SUBNET=$REQUEST_SUBNET
ZIVPN_PORT=$ZIVPN_PORT
HYSTERIA_PORT=$HYSTERIA_PORT
CUSTOM_PORT=$CUSTOM_PORT
UDPGW_ADDR=$UDPGW_ADDR
EOF
  chmod 600 "$CONF"

  # One self-signed certificate for the three hysteria servers. The app does
  # not verify it (these protocols never do), so it is kept across re-runs.
  if [ ! -s "$ETC/cert.pem" ] || [ ! -s "$ETC/key.pem" ]; then
    openssl req -x509 -newkey rsa:2048 -nodes -sha256 -days 3650 \
      -keyout "$ETC/key.pem" -out "$ETC/cert.pem" -subj "/CN=$PUBLIC_HOST" 2> /dev/null ||
      die "could not create the TLS certificate"
    chmod 600 "$ETC/key.pem"
  fi

  # Path MTU discovery is off in all three: a server's packets go to mina-udp
  # over loopback first, where any size passes, so a probe would "prove" a
  # size the real path to the client may not carry.
  cat > "$ETC/hysteria.json" <<EOF
{
  "listen": ":$HYSTERIA_PORT",
  "cert": "$ETC/cert.pem",
  "key": "$ETC/key.pem",
  "obfs": "$HYSTERIA_OBFS",
  "auth": {"mode": "external", "config": {"cmd": "/usr/local/bin/mina-udp-auth"}},
  "recv_window_conn": 16777216,
  "recv_window_client": 67108864,
  "max_conn_client": 4096,
  "disable_mtu_discovery": true
}
EOF
  cat > "$ETC/udp-custom.json" <<EOF
{
  "listen": ":$CUSTOM_PORT",
  "cert": "$ETC/cert.pem",
  "key": "$ETC/key.pem",
  "obfs": "$CUSTOM_OBFS",
  "alpn": "h3",
  "auth": {"mode": "external", "config": {"cmd": "/usr/local/bin/mina-udp-auth"}},
  "recv_window_conn": 16777216,
  "recv_window_client": 67108864,
  "max_conn_client": 4096,
  "disable_mtu_discovery": true
}
EOF
  cat > "$ETC/zivpn.yaml" <<EOF
listen: :$ZIVPN_PORT
tls:
  cert: $ETC/cert.pem
  key: $ETC/key.pem
obfs:
  type: salamander
  salamander:
    password: '$ZIVPN_OBFS'
auth:
  type: command
  command: /usr/local/bin/mina-udp-auth
quic:
  initStreamReceiveWindow: 8388608
  maxStreamReceiveWindow: 8388608
  initConnReceiveWindow: 20971520
  maxConnReceiveWindow: 20971520
  maxIdleTimeout: 60s
  maxIncomingStreams: 1024
  disablePathMTUDiscovery: true
udpIdleTimeout: 120s
EOF
  chmod 600 "$ETC"/*.json "$ETC"/*.yaml

  write_tools "$LIB"
  chmod 755 "$LIB/firewall.sh" "$LIB/udp.sh"
  ln -sfn "$LIB/udp.sh" /usr/local/bin/udp
}

tune() {
  step "Tuning the kernel for UDP throughput"
  local bbr=""
  modprobe tcp_bbr 2> /dev/null || true
  modprobe nf_conntrack 2> /dev/null || true
  if grep -qw bbr /proc/sys/net/ipv4/tcp_available_congestion_control 2> /dev/null; then
    bbr="net.core.default_qdisc = fq
net.ipv4.tcp_congestion_control = bbr"
  fi
  cat > /etc/sysctl.d/99-mina-udp.conf <<EOF
# MinaProNet UDP servers (install-udp.sh).
net.ipv4.ip_forward = 1
# QUIC wants large socket buffers; the default 208 KB cap throttles it and
# drops packets under load.
net.core.rmem_max = 33554432
net.core.wmem_max = 33554432
net.core.rmem_default = 1048576
net.core.wmem_default = 1048576
net.core.netdev_max_backlog = 16384
net.core.somaxconn = 8192
net.ipv4.udp_rmem_min = 16384
net.ipv4.udp_wmem_min = 16384
# Outgoing TCP (what the tunnels fetch for their clients).
net.ipv4.tcp_fastopen = 3
net.ipv4.tcp_mtu_probing = 1
net.ipv4.tcp_slow_start_after_idle = 0
net.ipv4.tcp_rmem = 4096 131072 33554432
net.ipv4.tcp_wmem = 4096 65536 33554432
$bbr
# A client that scatters its packets over many ports (UDP Request, and the
# app's Hysteria client, which uses another port for every packet) leaves one
# never-answered conntrack entry per port. The short timeout for unanswered
# UDP keeps those few; a full table drops packets.
net.netfilter.nf_conntrack_max = 1048576
net.netfilter.nf_conntrack_udp_timeout = 4
net.netfilter.nf_conntrack_udp_timeout_stream = 180
EOF
  printf 'tun\nnf_conntrack\n%s' "${bbr:+tcp_bbr
}" > /etc/modules-load.d/mina-udp.conf
  chmod 644 /etc/sysctl.d/99-mina-udp.conf /etc/modules-load.d/mina-udp.conf
  # -e: a key this kernel lacks (containers, old kernels) is skipped.
  sysctl -e -q -p /etc/sysctl.d/99-mina-udp.conf > /dev/null 2>&1 || true
}

unit() { # unit NAME DESCRIPTION EXEC [EXTRA-LINES]
  cat > "/etc/systemd/system/$1.service" <<EOF
[Unit]
Description=MinaProNet UDP: $2
After=network-online.target mina-udp-firewall.service
Wants=network-online.target mina-udp-firewall.service
StartLimitIntervalSec=0

[Service]
Type=simple
ExecStart=$3
Restart=always
RestartSec=2
LimitNOFILE=1048576
LimitNPROC=infinity
TasksMax=infinity
OOMScoreAdjust=-500
NoNewPrivileges=true
ProtectSystem=full
ProtectHome=true
PrivateTmp=true
${4:-}
[Install]
WantedBy=multi-user.target
EOF
  chmod 644 "/etc/systemd/system/$1.service"
}

# start_service NAME FILE...: (re)start the service only if one of the files
# it runs from changed since it was last started by this installer. Running
# the installer again with nothing new then leaves every client connected.
start_service() {
  local name=$1 stamp=$LIB/stamp-$1 sum
  shift
  sum=$(cat "/etc/systemd/system/$name.service" "$@" 2> /dev/null | sha256sum)
  if [ "$sum" = "$(cat "$stamp" 2> /dev/null)" ] && systemctl -q is-active "$name"; then
    return 0
  fi
  systemctl restart "$name"
  echo "$sum" > "$stamp"
}

services() {
  step "Installing the services"
  unit mina-udp-hysteria "hysteria v1 (UDP Hysteria, SlowUDP)" \
    "/usr/local/bin/mina-hysteria --no-check --log-level info server --config $ETC/hysteria.json"
  unit mina-udp-custom "UDP Custom" \
    "/usr/local/bin/mina-udp-custom --no-check --log-level info server --config $ETC/udp-custom.json"
  unit mina-udp-zivpn "ZIVPN UDP" \
    "/usr/local/bin/mina-zivpn server --disable-update-check --log-level info --config $ETC/zivpn.yaml" \
    "Environment=HYSTERIA_DISABLE_UPDATE_CHECK=1"
  unit mina-udp-request "UDP Request" \
    "/usr/local/bin/mina-udp request -listen $FRONT_PORT -mark $FRONT_MARK -hysteria-obfs $HYSTERIA_OBFS -hysteria-port $HYSTERIA_PORT -custom-port $CUSTOM_PORT -zivpn-port $ZIVPN_PORT -tun $REQUEST_TUN -net $REQUEST_NET -users $ETC/users.db -state /run/mina-udp/sessions" \
    "ExecStartPre=-/sbin/modprobe tun
RuntimeDirectory=mina-udp
RuntimeDirectoryMode=0700
RuntimeDirectoryPreserve=yes"
  unit mina-udp-udpgw "udpgw (UDP traffic of the hysteria modes)" \
    "/usr/local/bin/mina-udp udpgw -listen $UDPGW_ADDR"

  # Stays running: other tools (ufw, docker, an iptables-restore) can flush
  # rules at any time, and this puts them back within seconds.
  cat > /etc/systemd/system/mina-udp-firewall.service <<EOF
[Unit]
Description=MinaProNet UDP: firewall rules
After=network-pre.target
Wants=network-pre.target
StartLimitIntervalSec=0

[Service]
Type=simple
ExecStart=$LIB/firewall.sh watch
ExecStopPost=$LIB/firewall.sh stop
Restart=always
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF
  chmod 644 /etc/systemd/system/mina-udp-firewall.service
  systemctl daemon-reload
  systemctl enable -q mina-udp-firewall.service \
    mina-udp-udpgw mina-udp-hysteria mina-udp-custom mina-udp-zivpn mina-udp-request
  local cert="$ETC/cert.pem $ETC/key.pem" b=/usr/local/bin
  # shellcheck disable=SC2086
  {
    start_service mina-udp-firewall "$LIB/firewall.sh" "$CONF"
    start_service mina-udp-udpgw $b/mina-udp
    start_service mina-udp-hysteria $b/mina-hysteria "$ETC/hysteria.json" $cert
    start_service mina-udp-custom $b/mina-udp-custom "$ETC/udp-custom.json" $cert
    start_service mina-udp-zivpn $b/mina-zivpn "$ETC/zivpn.yaml" $cert
    start_service mina-udp-request $b/mina-udp
  }
}

first_account() {
  # Accounts of an earlier install stay as they are.
  [ -s "$ETC/users.db" ] && return 0
  local user=${UDP_USER:-} pass=${UDP_PASS:-} days=${UDP_DAYS:-}
  if [ -z "$user" ] && [ -t 0 ]; then
    echo
    read -r -p "First account - username [mina]: " user || true
    read -r -p "First account - password [random]: " pass || true
    read -r -p "First account - days until it expires, 0 = never [0]: " days || true
  fi
  user=${user:-mina}
  pass=${pass:-$(random 10)}
  /usr/local/bin/mina-udp user add "$user" "$pass" "${days:-0}" ||
    die "could not create the account (add one with: udp add USER PASSWORD [DAYS])"
}

verify() {
  step "Checking that every server is up"
  local i
  for i in $(seq 1 15); do
    if /usr/local/bin/udp status > /dev/null 2>&1; then
      /usr/local/bin/udp status
      return 0
    fi
    sleep 1
  done
  /usr/local/bin/udp status || true
  die "not every server came up; see: udp logs"
}

install_all() {
  preflight
  packages
  build
  configure
  tune
  first_account
  services
  verify
  /usr/local/bin/udp info || true
  cat <<EOF
${G}${B}Done.${N} The servers start on boot and restart themselves if they ever stop.
Manage accounts with:  ${B}udp${N}   (menu)   or   udp add USER PASSWORD [DAYS]
If your provider has its own firewall (security group), allow ${B}all UDP ports${N} there.
EOF
}

case "${1:-install}" in
  install) install_all ;;
  uninstall)
    [ "$(id -u)" = 0 ] || die "run as root"
    [ -x /usr/local/bin/udp ] || die "not installed"
    shift
    /usr/local/bin/udp uninstall "$@"
    ;;
  -h | --help | help) sed -n '2,38p' "$0" | sed 's/^# \{0,1\}//' ;;
  *) die "unknown command: $1 (install | uninstall)" ;;
esac
